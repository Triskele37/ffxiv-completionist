function dive(target: string): void {
    const targetDirs = fs.readdirSync(target);

    targetDirs.forEach((targetDir) => {
        const targetPath = path.join(target, targetDir);

        if(fs.lstatSync(targetPath).isDirectory()) dive(targetPath);
        else {
            doMap(targetPath);
        }
    });
}

function doMap(target: string): void {
    const rawFile = fs.readFileSync(target, 'utf8');
    const targetFile = JSON.parse(rawFile);

    if(targetFile.cCombo) targetFile.cCombo = mapChain(targetFile.cCombo);
    if(targetFile.tasks) {
        Object.keys(targetFile.tasks).forEach((taskKey) => {
            const task = targetFile.tasks[taskKey];
            if(task.cPrev) task.cPrev = mapChain(task.cPrev);
            if(task.cNext) task.cNext = mapChain(task.cNext);
            if(task.cSiblings) task.cSiblings = mapChain(task.cSiblings);
            if(task.cCombo) task.cCombo = mapChain(task.cCombo);
            if(task.cExclude) task.cExclude = mapChain(task.cExclude);
            if(task.cExclusive) task.cExclusive = mapChain(task.cExclusive);
            if(task.cPrevAt) task.cPrevAt = mapChain(task.cPrevAt);
            if(task.cSiblingsAt) task.cSiblingsAt = mapChain(task.cSiblingsAt);
            if(task.cComboAt) task.cComboAt = mapChain(task.cComboAt);
        });
    }

    const rawChanged = JSON.stringify(targetFile, null, 4);
    if(rawFile !== rawChanged) {
        console.log(`Mapping to: ${chalk.green(target)}`);
        fs.writeFileSync(target, rawChanged);
    }
}

function mapChain(chainOrChains) {
    if(typeof chainOrChains === 'number') {
        return chainOrChains;
    }

    if(typeof chainOrChains === 'string') {
        return map[chainOrChains] || chainOrChains;
    }

    if(Array.isArray(chainOrChains)) {
        return chainOrChains.map((chain) => mapChain(chain));
    }

    // is 'at' object
    Object.keys(chainOrChains).forEach((level) => {
        chainOrChains[level] = mapChain(chainOrChains[level]);
    });
    return chainOrChains;
}
