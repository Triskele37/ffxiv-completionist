import { ChangeStore } from '@service/store/migration/ChangeStore';

const CLOG = 'overall.logs.crafting-log';

/**
 * Crafting log changes from Generated Resources
 * - Massive ID consistency rekey from some using ItemResult's id to the Recipe itself
 * - Need to move books group out so indexing doesn't overlap its keys with recipes
 * - Minor group renames from 7.x
 * - Delete save data for belts
 */
export function migrateCrafting(store: ChangeStore): void {
    // Uniform Item id to Recipe id
    migrateCarpenter(store);
    migrateBlacksmith(store);
    migrateArmorer(store);
    migrateGoldsmith(store);
    migrateLeatherworker(store);
    migrateWeaver(store);
    migrateAlchemist(store);
    migrateCulinarian(store);
    migrateShared(store);

    // Group renaming
    migrateCrafterGroups(store, 'carpenter');
    migrateCrafterGroups(store, 'blacksmith');
    migrateCrafterGroups(store, 'armorer');
    migrateCrafterGroups(store, 'goldsmith');
    migrateCrafterGroups(store, 'leatherworker');
    migrateCrafterGroups(store, 'weaver');
    migrateCrafterGroups(store, 'alchemist');
    migrateCrafterGroups(store, 'culinarian');
}

function migrateCrafterGroups(store: ChangeStore, crafter: string): void {
    // Renames
    const HOUSING = `${CLOG}.${crafter}.special-recipes.housing`;
    store.moveGroup(`${HOUSING}.indoor`, `${HOUSING}.indoor-furnishings`, true);
    store.moveGroup(`${HOUSING}.outdoor`, `${HOUSING}.outdoor-furnishings`, true);
    store.moveGroup(`${HOUSING}.table-rugs`, `${HOUSING}.tables-and-rugs`, true);

    const SHARED = `${CLOG}.shared`;
    store.moveGroup(`${SHARED}.class.studium`, `${SHARED}.class.studium-deliveries`, true);
    store.moveGroup(`${SHARED}.tribal-quests`, `${SHARED}.society-quests`, true);

    // Restoration merge
    const RESTO = `${CLOG}.${crafter}.special-recipes.sidequests.restoration`;
    store.moveGroup(`${RESTO}-1`, RESTO, true);
    store.moveGroup(`${RESTO}-2`, RESTO, true);
    store.moveGroup(`${RESTO}-3`, RESTO, true);
    store.moveGroup(`${RESTO}-4`, RESTO, true);
}

